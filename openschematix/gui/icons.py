def draw_icon(cv, name: str, x: float, y: float, size: float, color: str, accent: str, width: float = 1.6,
              tag="icon", font_family="Helvetica"):
    """Draw icon `name` with its top-left at (x, y) on a Tk canvas."""
    ops = ICONS.get(name)
    if ops is None:
        ops = [("r", 4, 4, 20, 20), ("l", 4, 4, 20, 20)]
    k = size / 24.0
    w = max(1.0, width * k)

    def P(*vals):
        out = []
        for i in range(0, len(vals), 2):
            out += [x + vals[i] * k, y + vals[i + 1] * k]
        return out
    for op in ops:
        kind = op[0]
        acc = kind.endswith("!")
        kind = kind.rstrip("!")
        col = accent if acc else color
        args = op[1:]
        if kind == "l":
            cv.create_line(*P(*args), fill=col, width=w, capstyle="round", joinstyle="round", tags=tag)
        elif kind in ("p", "pf"):
            cv.create_polygon(*P(*args), outline=col, fill=col if kind == "pf" else "", width=w,
                              joinstyle="round", tags=tag)
        elif kind == "r":
            x1, y1, x2, y2 = P(*args)
            cv.create_rectangle(x1, y1, x2, y2, outline=col, width=w, tags=tag)
        elif kind in ("o", "of"):
            cx, cy, r = x + args[0] * k, y + args[1] * k, args[2] * k
            cv.create_oval(cx - r, cy - r, cx + r, cy + r, outline=col, fill=col if kind == "of" else "",
                           width=w if kind == "o" else 0, tags=tag)
        elif kind == "a":
            cx, cy, r, st, ex = args
            cx, cy, r = x + cx * k, y + cy * k, r * k
            cv.create_arc(cx - r, cy - r, cx + r, cy + r, start=st, extent=ex, style="arc", outline=col, width=w,
                          tags=tag)
        elif kind == "t":
            tx, ty, s, sz = args
            cv.create_text(x + tx * k, y + ty * k, text=s, fill=col, font=(font_family, -max(5, int(sz * k * 1.25)),
                                                                            "bold"), tags=tag)
